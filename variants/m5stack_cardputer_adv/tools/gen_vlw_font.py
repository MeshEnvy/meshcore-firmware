#!/usr/bin/env python3
"""Generate a LovyanGFX smooth (VLW) font header from a TrueType font.

Produces the same Unicode coverage as the original DejaVuSans_11 UI font
(Basic Latin, Latin-1, Latin Extended-A, Cyrillic, currency symbols,
arrows) at a chosen pixel size, as a PROGMEM byte array.

    python gen_vlw_font.py DejaVuSans.ttf 16 ../companion_radio/ui-cardputer/font_16.h

DejaVuSans.ttf ships with matplotlib (mpl-data/fonts/ttf) and most Linux
distributions. Requires Pillow and fontTools.
The generated DejaVu Sans bitmap data retains the font notices in
../LICENSE.DejaVu; distribute that notice with the generated font assets.
"""
import struct
import sys

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

RANGES = [
    (0x20, 0x7E),      # Basic Latin
    (0xA0, 0xFF),      # Latin-1 Supplement
    (0x100, 0x17F),    # Latin Extended-A
    (0x400, 0x4FF),    # Cyrillic
    (0x20A0, 0x20CF),  # Currency Symbols
    (0x2190, 0x21FF),  # Arrows
]
CONTROL = (0x09, 0x0A, 0x0D)  # zero-width placeholders, as in the original


def glyph(font, cp):
    ch = chr(cp)
    advance = round(font.getlength(ch))
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    w, h = right - left, bottom - top
    if w <= 0 or h <= 0:
        return (cp, 0, 0, advance, 0, 0), b""
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    # (unicode, height, width, xAdvance, dY above baseline, dX)
    return (cp, h, w, advance, -top, left), img.tobytes()


def build(ttf, px):
    font = ImageFont.truetype(ttf, px)
    cmap = TTFont(ttf).getBestCmap()
    records, bitmaps = [], []
    for cp in CONTROL:
        records.append((cp, 1, 1, 0, 2 * px, -px))
        bitmaps.append(b"\x00")
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            if cp not in cmap:
                continue
            rec, bmp = glyph(font, cp)
            records.append(rec)
            bitmaps.append(bmp)

    ascent = glyph(font, ord("d"))[0][4]
    d_p = glyph(font, ord("p"))[0]
    descent = d_p[1] - d_p[4]

    out = bytearray(struct.pack(">6i", len(records), 11, px, 0, ascent, descent))
    for rec in records:
        out += struct.pack(">7i", *rec, 0)
    for bmp in bitmaps:
        out += bmp
    name = (font.getname()[0] or "DejaVu Sans").encode()
    out += struct.pack(">i", len(name)) + name + b"\x00"
    return out, len(records)


def main():
    ttf, px, path = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    data, count = build(ttf, px)
    lines = [
        "#pragma once",
        "",
        "// Embedded DejaVu Sans bitmap data; see variants/m5stack_cardputer_adv/LICENSE.DejaVu.",
        f"// DejaVu Sans {px}px, {count} glyphs, generated by tools/gen_vlw_font.py",
        "",
        f"static const uint8_t DejaVuSans_{px}[] PROGMEM = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{path}: {count} glyphs, {len(data)} bytes")


if __name__ == "__main__":
    main()
